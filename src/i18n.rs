//! User interface translations. English is the source language; the
//! German table maps each English text to its translation.

use std::collections::HashMap;
use std::sync::atomic::{AtomicBool, Ordering};
use std::sync::OnceLock;

static GERMAN: AtomicBool = AtomicBool::new(false);

/// "de", "en" or anything else for the system language.
pub fn set_language(code: &str) {
    let german = match code {
        "de" => true,
        "en" => false,
        _ => sys_locale::get_locale().is_some_and(|l| l.to_ascii_lowercase().starts_with("de")),
    };
    GERMAN.store(german, Ordering::Relaxed);
}

pub fn is_german() -> bool {
    GERMAN.load(Ordering::Relaxed)
}

/// Translation of `text` in the current language.
pub fn tr(text: &'static str) -> &'static str {
    if !is_german() {
        return text;
    }
    static TABLE: OnceLock<HashMap<&'static str, &'static str>> = OnceLock::new();
    TABLE
        .get_or_init(|| DE.iter().copied().collect())
        .get(text)
        .copied()
        .unwrap_or(text)
}

/// Translates `template` and fills its `{}` placeholders with `args`.
pub fn trf(template: &'static str, args: &[&dyn std::fmt::Display]) -> String {
    let mut out = String::new();
    let mut args = args.iter();
    let mut parts = tr(template).split("{}").peekable();
    while let Some(part) = parts.next() {
        out.push_str(part);
        if parts.peek().is_some() {
            if let Some(a) = args.next() {
                out.push_str(&a.to_string());
            }
        }
    }
    out
}

